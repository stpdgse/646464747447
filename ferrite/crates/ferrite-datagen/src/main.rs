//! `ferrite-datagen`: turns the official server's data reports into Rust tables.
//!
//! ```text
//! cargo datagen --jar /path/to/server.jar
//! ```
//!
//! The tool runs the vanilla data generator (`--reports --server`), reads `version.json` from the
//! jar, validates every structural assumption the runtime relies on, and writes formatted Rust
//! into `crates/ferrite-data/src/generated`. Nothing from the jar is copied other than ids, names
//! and block-state layouts.

mod blocks;
mod configuration;
mod items;
mod loot;
mod meta;
mod packets;
mod registries;
mod shapes;
mod util;

use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::{Context, Result, bail};
use clap::Parser;
use sha1::{Digest, Sha1};

#[derive(Parser, Debug)]
#[command(version, about)]
struct Args {
    /// Path to the official `server.jar`.
    #[arg(long)]
    jar: PathBuf,
    /// Java executable (must be the JDK the jar requires, e.g. 25 for 26.x).
    #[arg(long, default_value = "java")]
    java: PathBuf,
    /// Reuse an existing data-generator output directory instead of running the jar.
    #[arg(long)]
    reports: Option<PathBuf>,
    /// Where to keep the data-generator output (default: a temporary directory).
    #[arg(long)]
    work_dir: Option<PathBuf>,
    /// Output directory for the generated Rust files.
    #[arg(long, default_value = "crates/ferrite-data/src/generated")]
    out: PathBuf,
    /// Skip running rustfmt on the output.
    #[arg(long)]
    no_fmt: bool,
}

#[derive(Debug)]
pub struct GenContext {
    pub reports: PathBuf,
    pub header: String,
}

fn main() -> Result<()> {
    let args = Args::parse();

    let jar_bytes = std::fs::read(&args.jar).with_context(|| format!("reading {:?}", args.jar))?;
    let jar_sha1 = hex(&Sha1::digest(&jar_bytes));
    let version = meta::read_version_json(&jar_bytes)?;
    eprintln!(
        "server.jar: Minecraft {} (protocol {}, world {}), sha1 {}",
        version.id, version.protocol_version, version.world_version, jar_sha1
    );

    let _tmp;
    let reports_root = match (&args.reports, &args.work_dir) {
        (Some(r), _) => r.clone(),
        (None, Some(w)) => run_generator(&args.java, &args.jar, w)?,
        (None, None) => {
            _tmp = tempfile::tempdir()?;
            run_generator(&args.java, &args.jar, _tmp.path())?
        }
    };

    let header = format!(
        "// @generated by ferrite-datagen from Minecraft {} (server.jar sha1 {}). DO NOT EDIT.\n",
        version.id, jar_sha1
    );
    let cx = GenContext { reports: reports_root.join("reports"), header };

    std::fs::create_dir_all(&args.out)?;
    let regs = registries::load(&cx)?;
    let files = [
        ("meta.rs", meta::generate(&cx, &version)),
        ("packets.rs", packets::generate(&cx)?),
        ("registries.rs", registries::generate(&cx, &regs)?),
        ("blocks.rs", blocks::generate(&cx, &regs)?),
        ("shapes.rs", shapes::generate(&cx)?),
        ("items.rs", items::generate(&cx, &regs)?),
        ("loot.rs", loot::generate(&cx)?),
        ("configuration.rs", configuration::generate(&cx, &regs)?),
        ("mod.rs", mod_rs(&cx)),
    ];
    for (name, content) in &files {
        let path = args.out.join(name);
        std::fs::write(&path, content).with_context(|| format!("writing {path:?}"))?;
        eprintln!("wrote {} ({} bytes)", path.display(), content.len());
    }
    if !args.no_fmt {
        let paths: Vec<_> = files.iter().map(|(n, _)| args.out.join(n)).collect();
        let status = Command::new("rustfmt")
            .args(["--edition", "2024"])
            .args(&paths)
            .status()
            .context("running rustfmt")?;
        if !status.success() {
            bail!("rustfmt failed");
        }
    }
    Ok(())
}

fn mod_rs(cx: &GenContext) -> String {
    format!(
        "{}\npub mod blocks;\npub mod configuration;\npub mod items;\npub mod loot;\npub mod meta;\npub mod packets;\npub mod registries;\npub mod shapes;\n",
        cx.header
    )
}

fn run_generator(java: &Path, jar: &Path, work: &Path) -> Result<PathBuf> {
    std::fs::create_dir_all(work)?;
    // Absolute paths, because the jar runs with the work directory as its cwd (it writes `logs/`
    // and a `versions/` cache next to wherever it is started, which must not be the repository).
    let work = std::fs::canonicalize(work)?;
    let jar = std::fs::canonicalize(jar)?;
    let out = work.join("out");
    let _ = std::fs::remove_dir_all(&out);
    eprintln!("running vanilla data generator into {}", out.display());
    let status = Command::new(java)
        .current_dir(&work)
        .arg("-DbundlerMainClass=net.minecraft.data.Main")
        .arg("-jar")
        .arg(&jar)
        .args(["--reports", "--server", "--output"])
        .arg(&out)
        .status()
        .with_context(|| format!("launching {java:?}"))?;
    if !status.success() {
        bail!("data generator exited with {status}");
    }
    run_shape_dump(java, &work, &out)?;
    Ok(out)
}

/// Compiles and runs `java/ShapeDump.java` against the libraries and server jar the bundler
/// unpacked into `work`, writing `out/shapes.txt`.
fn run_shape_dump(java: &Path, work: &Path, out: &Path) -> Result<()> {
    let jars = unpacked_classpath(work)?;
    let sep = if cfg!(windows) { ";" } else { ":" };
    let cp = jars.iter().map(|p| p.display().to_string()).collect::<Vec<_>>().join(sep);
    let source = Path::new(env!("CARGO_MANIFEST_DIR")).join("java/ShapeDump.java");
    let classes = work.join("shapedump-classes");
    let _ = std::fs::remove_dir_all(&classes);
    std::fs::create_dir_all(&classes)?;
    let javac = java.with_file_name(if cfg!(windows) { "javac.exe" } else { "javac" });
    let javac = if javac.exists() { javac } else { PathBuf::from("javac") };
    eprintln!("compiling and running ShapeDump");
    let status = Command::new(&javac)
        .args(["-nowarn", "-cp", &cp, "-d"])
        .arg(&classes)
        .arg(&source)
        .status()
        .with_context(|| format!("launching {javac:?}"))?;
    if !status.success() {
        bail!("javac failed for ShapeDump.java (a JDK, not just a JRE, is required)");
    }
    let run_cp = format!("{}{sep}{cp}", classes.display());
    let status = Command::new(java)
        .current_dir(work)
        .args(["-cp", &run_cp, "ShapeDump"])
        .arg(out.join("shapes.txt"))
        .status()
        .with_context(|| format!("launching {java:?}"))?;
    if !status.success() {
        bail!("ShapeDump exited with {status}");
    }
    Ok(())
}

/// The server jar and every library jar the bundler extracted under `work`.
fn unpacked_classpath(work: &Path) -> Result<Vec<PathBuf>> {
    fn walk(dir: &Path, out: &mut Vec<PathBuf>) -> Result<()> {
        if !dir.exists() {
            return Ok(());
        }
        for entry in std::fs::read_dir(dir)? {
            let path = entry?.path();
            if path.is_dir() {
                walk(&path, out)?;
            } else if path.extension().is_some_and(|e| e == "jar") {
                out.push(path);
            }
        }
        Ok(())
    }
    let mut jars = Vec::new();
    walk(&work.join("versions"), &mut jars)?;
    walk(&work.join("libraries"), &mut jars)?;
    jars.sort();
    ensure_non_empty(&jars)?;
    Ok(jars)
}

fn ensure_non_empty(jars: &[PathBuf]) -> Result<()> {
    if jars.is_empty() {
        bail!("the bundler did not unpack any jars");
    }
    Ok(())
}

fn hex(bytes: &[u8]) -> String {
    use std::fmt::Write;
    bytes.iter().fold(String::new(), |mut s, b| {
        let _ = write!(s, "{b:02x}");
        s
    })
}
