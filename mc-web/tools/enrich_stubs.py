"""Rewrite stub-classes.txt with true class hierarchies from tools/stubinfo/StubInfo.java output.

usage: enrich_stubs.py STUBS_FILE STUBINFO_OUTPUT
Supertypes discovered by StubInfo are added too, so every placeholder has a consistent hierarchy.
"""
import sys

stubs, info = sys.argv[1], sys.argv[2]
old = [l.rstrip('\n') for l in open(stubs) if l.strip()]
known = {}
for l in open(info):
    p = l.split()
    if p and p[0] != 'unknown':
        known[p[1]] = l.strip()
out = ['# generated by tools/genstubs.py + tools/enrich_stubs.py: kind name [parent|-] [abstract|-] [ifaces,...]']
done = set()
for l in old:
    if l.startswith('#'):
        continue
    p = l.split()
    if p[0] == 'lenient':
        out.append(l)
    elif p[1] in known:
        out.append(known[p[1]])
        done.add(p[1])
    else:
        out.append(l)
        done.add(p[1])
for n, l in known.items():
    if n not in done:
        out.append(l)
open(stubs, 'w').write('\n'.join(out) + '\n')
print(len(known), 'enriched;', len(out), 'lines')
