create function t.near(a double precision, b double precision, tol double precision, msg text) returns void language plpgsql as $$
begin if abs(a - b) > tol then raise exception 'FAILED: % (got %, expected %)', msg, a, b; end if; raise notice 'ok   %', msg; end $$;

-- ============================================================ Glicko-2 vs the independent npm "glicko2" library
-- Expected values were generated by node (glicko2@1.2.4, tau 0.5) and pasted here.
create function t.check_glicko(r float8, rd float8, vol float8, orr float8, ord float8, s float8, er float8, erd float8, ev float8, name text)
returns void language plpgsql as $$
declare x record;
begin
  select * into x from private.glicko2(r, rd, vol, orr, ord, s);
  perform t.near(x.new_r, er, 0.01, name || ': rating');
  perform t.near(x.new_rd, erd, 0.01, name || ': RD');
  perform t.near(x.new_vol, ev, 0.0001, name || ': volatility');
end $$;
select t.check_glicko(1500, 350, 0.06, 1500, 350, 1,   1662.311, 290.319, 0.06,     'fresh vs fresh, win');
select t.check_glicko(1500, 350, 0.06, 1500, 350, 0.5, 1500,     290.319, 0.059999, 'fresh vs fresh, draw');
select t.check_glicko(1800, 80, 0.06, 1500, 60, 1,     1805.551, 79.599,  0.059999, 'favourite wins');
select t.check_glicko(1800, 80, 0.06, 1500, 60, 0,     1769.722, 79.599,  0.060007, 'favourite loses');
select t.check_glicko(1500, 200, 0.06, 1400, 30, 1,    1563.564, 175.403, 0.059999, 'paper-style example');
select t.check_glicko(1200, 350, 0.06, 2100, 50, 0,    1195.941, 346.116, 0.06,     'big underdog loses');
select t.check_glicko(2400, 60, 0.07, 2300, 110, 0.5,  2397.366, 60.447,  0.069996, 'strong player draws');

-- ============================================================ perf mapping
select t.ok(private.perf_of('standard', 60000, 0) = 'bullet', '1+0 is bullet');
select t.ok(private.perf_of('standard', 180000, 0) = 'blitz', '3+0 is blitz');
select t.ok(private.perf_of('standard', 180000, 2000) = 'blitz', '3+2 is blitz');
select t.ok(private.perf_of('standard', 120000, 1000) = 'bullet', '2+1 is bullet');
select t.ok(private.perf_of('standard', 600000, 0) = 'rapid', '10+0 is rapid');
select t.ok(private.perf_of('chess960', 60000, 0) = 'chess960', 'variants have their own rating');

-- ============================================================ rated flow through the real functions
set role authenticated; select t.as_user(:'erin');
select t.ok((select public.server_quick_pair('s3cret', 'standard', 180000, 2000, :'fen', true) ? 'seek'), 'rated seek waits');
select t.as_user(:'finn');
select t.ok((select public.server_quick_pair('s3cret', 'standard', 180000, 2000, :'fen', false) ? 'seek'), 'a casual request does not match a rated seek');
select t.as_user(:'gina');
select t.ok((select public.server_quick_pair('s3cret', 'standard', 180000, 2000, :'fen', true) ? 'game'), 'rated matches rated');
reset role;
select id as rg, white_id as rw, black_id as rb from public.games where rated order by created_at desc limit 1 \gset
select t.ok((select white_rating = 1500 and black_rating = 1500 from public.games where id = :'rg'), 'ratings are snapshotted at the start (1500 for newcomers)');
select t.ok((select count(*) from public.ratings) = 0, 'no rating rows until a rated game finishes');

-- white resigns after a few moves -> black (the winner) gains, white loses
update public.games set moves = '{e2e4,e7e5,g1f3,b8c6}' where id = :'rg';
set role authenticated; select t.as_user(:'rw');
select t.ok((select status = 'finished' and result = '0-1' from public.server_resign('s3cret', :'rg')), 'rated game finished by resignation');
reset role;
select t.ok((select count(*) from public.ratings where perf = 'blitz') = 2, 'both players now have a blitz rating');
select t.near((select rating from public.ratings where user_id = :'rb' and perf = 'blitz'), 1662.311, 0.01, 'winner gains like a fresh-vs-fresh win');
select t.near((select rating from public.ratings where user_id = :'rw' and perf = 'blitz'), 3000 - 1662.311, 0.01, 'loser drops by the same amount');
select t.near((select rd from public.ratings where user_id = :'rw' and perf = 'blitz'), 290.319, 0.01, 'RD shrinks for both');
select t.ok((select games = 1 from public.ratings where user_id = :'rw' and perf = 'blitz'), 'game count recorded');
select t.ok((select count(*) = 2 and bool_and(rating_after <> rating_before) from public.rating_history where game_id = :'rg'), 'history has a row per player');
select t.near((select rating_after - rating_before from public.rating_history where game_id = :'rg' and user_id = :'rb'), 162, 1, 'history stores the gain');

-- applying twice never double counts
select private.apply_ratings(g) from public.games g where id = :'rg';
select t.ok((select games = 1 from public.ratings where user_id = :'rw' and perf = 'blitz'), 'ratings are applied exactly once');

-- the next game snapshots the new ratings
select t.new_game(:'rw', :'rb') as nx \gset
select t.ok((select white_rating = round(3000 - 1662.311) and black_rating = 1662 from public.games where id = :'nx'), 'next game snapshots updated ratings');
update public.games set status = 'aborted', reason = 'aborted' where id = :'nx';

-- ============================================================ casual games and aborts never touch ratings
select t.new_game(:'rw', :'rb', moves => '{e2e4,e7e5}') as cg \gset
set role authenticated; select t.as_user(:'rw');
select t.ok((select status = 'finished' from public.server_resign('s3cret', :'cg')), 'casual game finished');
reset role;
select t.ok((select games = 1 from public.ratings where user_id = :'rw' and perf = 'blitz'), 'casual games do not change ratings');
select t.ok((select count(*) from public.rating_history where game_id = :'cg') = 0, 'no history for casual games');

-- ============================================================ draws, timeouts, variants
create function t.rated_game(w uuid, b uuid, v text, tm int, inc int, mv text[]) returns uuid language sql as $$
  insert into public.games (variant, initial_fen, white_id, black_id, time_initial_ms, time_inc_ms, white_clock_ms, black_clock_ms, moves, rated)
  values (v, 'rnbqkbnr/pppppppp/8/8/8/8/PPPPPPPP/RNBQKBNR w KQkq - 0 1', w, b, tm, inc, tm, tm, mv, true) returning id $$;

select t.rated_game(:'erin', :'finn', 'standard', 600000, 0, '{e2e4,e7e5,g1f3,b8c6}') as dg \gset
set role authenticated; select t.as_user(:'erin');
select public.server_draw('s3cret', :'dg', 'offer');
select t.as_user(:'finn');
select t.ok((select status = 'finished' and result = '1/2-1/2' from public.server_draw('s3cret', :'dg', 'accept')), 'rated draw by agreement');
reset role;
select t.near((select rating from public.ratings where user_id = :'rw' and perf = 'rapid'), 1500, 0.01, 'a draw between equal newcomers keeps 1500 (rapid)');
select t.near((select rd from public.ratings where user_id = :'rw' and perf = 'rapid'), 290.319, 0.01, 'a draw still reduces uncertainty');

select t.rated_game(:'erin', :'finn', 'chess960', 600000, 0, '{e2e4,e7e5}') as tg \gset
update public.games set white_clock_ms = 500, clock_updated_at = clock_timestamp() - interval '2 seconds' where id = :'tg';
set role authenticated; select t.as_user(:'gina');
select t.ok((select status = 'finished' and result = '0-1' and reason = 'timeout' from public.server_claim_timeout('s3cret', :'tg')), 'a bystander claims a rated timeout');
reset role;
select t.ok((select count(*) from public.ratings where perf = 'chess960' and user_id in (:'erin', :'finn')) = 2, 'timeouts update the variant rating');
select t.ok((select rating > 1500 from public.ratings where user_id = :'finn' and perf = 'chess960'), 'the player who did not flag gains');

select t.rated_game(:'erin', :'finn', 'standard', 60000, 0, '{e2e4}') as ag \gset
set role authenticated; select t.as_user(:'erin');
select t.ok((select status = 'aborted' from public.server_abort('s3cret', :'ag')), 'aborted rated game');
reset role;
select t.ok((select count(*) from public.rating_history where game_id = :'ag') = 0, 'aborted games are never rated');

