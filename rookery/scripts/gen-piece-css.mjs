// Generates src/components/chess/pieces.css: one rule per piece per set, from the sets listed in themes.ts.
// Run with: node scripts/gen-piece-css.mjs
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const themes = readFileSync("src/lib/chess/themes.ts", "utf8");
const ids = [...themes.matchAll(/\{ id: "([a-z0-9]+)", label: "[^"]+", author:/g)].map((m) => m[1]);
const roles = { pawn: "P", knight: "N", bishop: "B", rook: "R", queen: "Q", king: "K" };

let css = "/* GENERATED by scripts/gen-piece-css.mjs: do not edit by hand. */\n";
for (const id of ids) {
  for (const [role, ch] of Object.entries(roles)) {
    for (const [color, c] of [["white", "w"], ["black", "b"]]) {
      const file = `public/pieces/${id}/${c}${ch}.svg`;
      if (!existsSync(file)) throw new Error(`Missing ${file}`);
      css += `.piece-set-${id} .cg-wrap piece.${role}.${color} { background-image: url("/pieces/${id}/${c}${ch}.svg"); }\n`;
    }
  }
}
writeFileSync("src/components/chess/pieces.css", css);
console.log(`Wrote ${ids.length} sets, ${ids.length * 12} rules`);
